export type Lang = "en" | "pt";
type Vars = Record<string, string | number>;
export type Translate = (key: MessageKey, vars?: Vars) => string;

const catalogs: Record<Lang, Record<MessageKey, string>> = { en, pt };
const STORAGE_KEY = "sicxe-lang";

function format(template: string, vars?: Vars): string {
    return vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match)) : template;
}

type I18n = { lang: Lang; setLang: (lang: Lang) => void; t: Translate };

// Without a provider (tests, isolated components) the interface is English.
const I18nContext = createContext<I18n>({ lang: "en", setLang: () => {}, t: (key, vars) => format(en[key], vars) });

// The chosen language lives in localStorage; this keeps it for the visit when storage is blocked.
let sessionLang: Lang | null = null;
const listeners = new Set<() => void>();

function storedLang(): Lang {
    if (sessionLang) return sessionLang;
    try {
        const stored = localStorage.getItem(STORAGE_KEY);
        if (stored === "en" || stored === "pt") return stored;
    } catch {
        // Storage blocked: fall back to the browser language.
    }
    return navigator.languages?.some((language) => language.toLowerCase().startsWith("pt")) ? "pt" : "en";
}

function subscribe(listener: () => void): () => void {
    listeners.add(listener);
    window.addEventListener("storage", listener); // another tab switched
    return () => {
        listeners.delete(listener);
        window.removeEventListener("storage", listener);
    };
}

function storeLang(next: Lang): void {
    try {
        localStorage.setItem(STORAGE_KEY, next);
    } catch {
        sessionLang = next;
    }
    listeners.forEach((listener) => listener());
}

export function I18nProvider({ children }: { children: ReactNode }) {
    // English on the server render; the browser's choice applies on hydration.
    const lang = useSyncExternalStore(subscribe, storedLang, () => "en" as const);
    useEffect(() => {
        document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
    }, [lang]);

    const setLang = useCallback((next: Lang) => storeLang(next), []);
    const t = useCallback<Translate>((key, vars) => format(catalogs[lang][key], vars), [lang]);
    const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
    return useContext(I18nContext);
}

export function useT(): Translate {
    return useContext(I18nContext).t;
}

export function LanguageSwitch() {
    const { lang, setLang, t } = useI18n();
    return (
        <div role="group" aria-label={t("lang.label")} className="flex shrink-0 overflow-hidden rounded border border-zinc-700 text-xs">
            {(["en", "pt"] as const).map((option) => (
                <button
                    key={option}
                    type="button"
                    lang={option === "pt" ? "pt-BR" : "en"}
                    aria-pressed={lang === option}
                    onClick={() => setLang(option)}
                    className="px-2 py-1 font-medium uppercase text-zinc-300 hover:bg-zinc-800 hover:text-zinc-100 focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-blue-400 aria-pressed:bg-zinc-700 aria-pressed:text-white"
                >
                    {option === "pt" ? "PT" : "EN"}
                </button>
            ))}
        </div>
    );
}
